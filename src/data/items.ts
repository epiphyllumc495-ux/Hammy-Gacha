export function getRandomItem(): GachaItem {
  const rand = Math.random() * 100;
  let targetRarity: Rarity = 'common';

  if (rand < 5) {
    targetRarity = 'legendary';
  } else if (rand < 15) { // 5 to 15 = 10%
    targetRarity = 'epic';
  } else if (rand < 40) { // 15 to 40 = 25%
    targetRarity = 'rare';
  } else { // 40 to 100 = 60%
    targetRarity = 'common';
  }

  const pool = GACHA_ITEMS.filter((item) => item.rarity === targetRarity);
  return pool[Math.floor(Math.random() * pool.length)];
}

